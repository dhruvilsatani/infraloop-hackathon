"""Output of a Bundle: a README for the files (MANIFEST.md), a zip for the web page, or a folder for the command line."""
import io
import os
import zipfile

ROOT = "infraloop-generated"


def manifest(bundle):
    L = ["# Files generated by InfraLoop", "",
         "Copy the files you want into your repository, **after reading the notes below**. They were written by fixed templates from the scan of your project, "
         "not by an AI model, and none of them was run against your app. InfraLoop never edits files you already have.", ""]
    t = bundle.target
    if bundle.implementation and not t:
        L += ["**Start with `IMPLEMENTATION.md`:** it says, step by step, what to do with these files.", ""]
    if t:
        price = f" The report priced it at about {t['monthly_eur']:.2f} EUR/month." if t.get("monthly_eur") is not None else ""
        L += [f"**Your choice:** {t['label']}.{price} Read `SETUP.md` first: it explains in plain words what this choice gives you and what you give up. "
              "Then follow `IMPLEMENTATION.md`, which says what to do with these files, step by step.", ""]
        if not t.get("files"):
            L += ["No infrastructure files exist for this choice yet. The basic files below are provider-neutral and still apply.", ""]
    if not bundle.files:
        L += ["No new files were generated: the scan found no missing file that a template can create."
              + (" See the fixes below for files you already have." if bundle.advice else ""), ""]
    for f in bundle.files:
        fixes = f"Fixes the gap `{f.gap}`." if f.gap else "A supporting file for the others (it does not close a gap by itself)."
        L += [f"## `{f.path}`", f"{f.title}. {fixes} Confidence: **{f.confidence}**.", ""]
        if f.assumptions:
            L += ["Assumed:"] + [f"- {a}" for a in f.assumptions] + [""]
        if f.review:
            L += ["Check before you use it:"] + [f"- {r}" for r in f.review] + [""]
    if bundle.advice:
        L += ["## Fixes for files you already have", "",
              "These gaps are about files that exist in your repository. Nothing below was applied: InfraLoop never edits existing files, so make each change by hand.", ""]
        for a in bundle.advice:
            L += [f"### {a.title}", f"Gap: `{a.gap}`."]
            if a.found:
                L += [f"Found: {a.found}"]
            L += [""]
            at = next((i for i, st in enumerate(a.steps) if st.rstrip().endswith(":")), len(a.steps) - 1)   # the step that introduces the snippet
            for i, step in enumerate(a.steps):
                L += [f"{i + 1}. {step}"]
                if a.snippet and i == at:
                    L += ["", f"```{a.snippet_lang}", a.snippet, "```", ""]
            L += [""]
    if bundle.skipped:
        L += ["## Not generated", ""] + [f"- `{s.gap}`: {s.reason}" for s in bundle.skipped] + [""]
    return "\n".join(L)


def to_zip_bytes(bundle):
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr(f"{ROOT}/MANIFEST.md", manifest(bundle))
        if bundle.implementation:
            z.writestr(f"{ROOT}/IMPLEMENTATION.md", bundle.implementation)
        if bundle.brief:
            z.writestr(f"{ROOT}/SETUP.md", bundle.brief)
        for f in bundle.files:
            z.writestr(f"{ROOT}/{f.path}", f.content)
    return buf.getvalue()


def write_to_dir(bundle, out_dir):
    """Writes the files under out_dir. Refuses to touch anything that already exists."""
    if os.path.exists(out_dir) and os.listdir(out_dir):
        raise FileExistsError(f"{out_dir} already exists and is not empty. Choose a new folder: InfraLoop never overwrites files.")
    written = []
    for name, text in [("MANIFEST.md", manifest(bundle))] + ([("IMPLEMENTATION.md", bundle.implementation)] if bundle.implementation else []) + ([("SETUP.md", bundle.brief)] if bundle.brief else []) + [(f.path, f.content) for f in bundle.files]:
        target = os.path.join(out_dir, name)
        os.makedirs(os.path.dirname(target) or out_dir, exist_ok=True)
        with open(target, "x", encoding="utf-8") as fh:
            fh.write(text)
        written.append(target)
    return written
